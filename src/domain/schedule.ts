export type DueState = 'overdue' | 'today' | 'soon' | 'upcoming' | 'done';

export function dueState(task: Pick<CareTask, 'dueDate' | 'doneAt'>, plan: SchedulePlan, ref: ISODate = todayISO()): DueState {
  if (task.doneAt) return 'done';
  const diff = daysBetween(ref, task.dueDate);
  if (diff < 0) return 'overdue';
  if (diff === 0) return 'today';
  if (diff <= plan.reminderLeadDays) return 'soon';
  return 'upcoming';
}

/** Aufgaben, die jetzt Aufmerksamkeit brauchen (für „Heute"). */
export function isActionable(task: Pick<CareTask, 'dueDate' | 'doneAt'>, plan: SchedulePlan, ref: ISODate = todayISO()): boolean {
  const s = dueState(task, plan, ref);
  return s === 'overdue' || s === 'today' || s === 'soon';
}

