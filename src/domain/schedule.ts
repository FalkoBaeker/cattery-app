/**
 * Der automatische Wurf-Fahrplan.
 *
 * Aus einem einzigen Datum — dem Geburtstag — ergibt sich der komplette
 * Ablauf der ersten zwölf Wochen. Siehe docs/ANFORDERUNGEN.md.
 *
 * Diese Datei ist absichtlich frei von React und (bis auf `syncLitterSchedule`)
 * frei von Datenbankzugriffen, damit sie vollständig testbar bleibt.
 */

import type { CareTask, CareTaskKind, ID, ISODate, Kitten, Litter, SchedulePlan, Settings } from '../types';
import { addWeeks, daysBetween, todayISO } from '../lib/date';
import { db, insert, patch } from '../db/db';

export interface PlannedTask {
  /** Stabiler Schlüssel zur Wiedererkennung beim Neuberechnen. */
  planKey: string;
  kind: CareTaskKind;
  title: string;
  detail?: string;
  dueDate: ISODate;
  /** Leer = gilt für den ganzen Wurf; gesetzt = nur für dieses Kitten. */
  kittenId?: ID;
  week: number;
}

/** Kitten, für die keine Kastration geplant wird. */
function skipsNeutering(k: Kitten): boolean {
  return (
    k.saleStatus === 'sold_breeding_reserved' || k.saleStatus === 'deceased' || k.stillborn
  );
}

/** Kitten, die überhaupt keine Aufgaben mehr brauchen. */
function isGone(k: Kitten): boolean {
  return k.stillborn || k.saleStatus === 'deceased';
}

/**
 * Erzeugt den vollständigen Fahrplan für einen Wurf.
 * Ohne Geburtsdatum gibt es nichts zu planen.
 */
export function planCareTasks(
  litter: Pick<Litter, 'birthDate'>,
  kittens: Kitten[],
  plan: SchedulePlan,
): PlannedTask[] {
  const birth = litter.birthDate;
  if (!birth) return [];

  const tasks: PlannedTask[] = [];
  const living = kittens.filter((k) => !isGone(k));

  // --- Entwurmung: wurfweit ---------------------------------------
  plan.dewormingWeeks.forEach((week, i) => {
    tasks.push({
      planKey: `deworming:${i + 1}`,
      kind: 'deworming',
      title: `Entwurmung ${i + 1}. Mal`,
      detail: plan.dewormingDrug,
      dueDate: addWeeks(birth, week),
      week,
    });
  });

  // --- Impfungen: wurfweit ----------------------------------------
  plan.vaccinationWeeks.forEach((week, i) => {
    tasks.push({
      planKey: `vaccination:${i + 1}`,
      kind: 'vaccination',
      title: `${i + 1}. Impfung`,
      dueDate: addWeeks(birth, week),
      week,
    });
  });

  // --- Chippen: wurfweit ------------------------------------------
  tasks.push({
    planKey: 'chip',
    kind: 'chip',
    title: 'Chippen',
    detail: 'Vorher aktuelles Gewicht erfassen',
    dueDate: addWeeks(birth, plan.chipWeek),
    week: plan.chipWeek,
  });

  // --- Kastration: je Kitten, entfällt bei Zuchtvorbehalt ----------
  for (const k of living) {
    if (skipsNeutering(k)) continue;
    tasks.push({
      planKey: `neuter:${k.id}`,
      kind: 'neuter',
      title: 'Kastration',
      detail: 'Vorher aktuelles Gewicht erfassen',
      dueDate: addWeeks(birth, plan.neuterWeek),
      kittenId: k.id,
      week: plan.neuterWeek,
    });
  }

  // --- Wurfmeldung an den Verein ----------------------------------
  tasks.push({
    planKey: 'litter_registration',
    kind: 'litter_registration',
    title: 'Wurfmeldung fällig',
    detail: 'Frist des Vereins',
    dueDate: addWeeks(birth, plan.litterRegistrationWeek),
    week: plan.litterRegistrationWeek,
  });

  // --- Abgabe frühestens erlaubt ----------------------------------
  tasks.push({
    planKey: 'handover_allowed',
    kind: 'handover_allowed',
    title: 'Abgabe ab jetzt erlaubt',
    detail: `Frühestens nach ${plan.handoverWeek} Wochen`,
    dueDate: addWeeks(birth, plan.handoverWeek),
    week: plan.handoverWeek,
  });

  return tasks.sort((a, b) => a.dueDate.localeCompare(b.dueDate) || a.planKey.localeCompare(b.planKey));
}

/**
 * Gleicht den gespeicherten Fahrplan eines Wurfes mit dem berechneten ab.
 *
 * - Neue Punkte werden angelegt.
 * - Verschobene Fälligkeiten werden aktualisiert, solange nicht erledigt.
 * - Weggefallene Punkte (z. B. Kastration nach Umstellung auf Zuchtvorbehalt)
 *   werden gelöscht — aber nur, wenn sie noch nicht erledigt sind.
 * - Erledigte Punkte bleiben immer unangetastet.
 */
export async function syncLitterSchedule(litterId: ID, settings: Settings): Promise<void> {
  const litter = await db.litters.get(litterId);
  if (!litter) return;
  const kittens = await db.kittens.where('litterId').equals(litterId).toArray();
  const planned = planCareTasks(litter, kittens, settings.schedule);

  const existing = await db.careTasks.where('litterId').equals(litterId).toArray();
  const auto = existing.filter((t) => t.autoGenerated);
  const byKey = new Map(auto.map((t) => [t.planKey ?? '', t]));

  for (const p of planned) {
    const current = byKey.get(p.planKey);
    if (!current) {
      await insert(db.careTasks, {
        kind: p.kind,
        title: p.title,
        detail: p.detail,
        dueDate: p.dueDate,
        litterId,
        kittenId: p.kittenId,
        autoGenerated: true,
        planKey: p.planKey,
      });
      continue;
    }
    byKey.delete(p.planKey);
    if (current.doneAt) continue;
    if (current.dueDate !== p.dueDate || current.title !== p.title) {
      await patch(db.careTasks, current.id, { dueDate: p.dueDate, title: p.title, detail: p.detail });
    }
  }

  // Was übrig bleibt, gehört nicht mehr zum Plan.
  for (const orphan of byKey.values()) {
    if (orphan.doneAt) continue;
    await db.careTasks.delete(orphan.id);
  }
}

