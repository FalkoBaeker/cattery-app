export interface LitterPauseCheck {
  allowed: boolean;
  /** Anzahl Würfe im Betrachtungszeitraum inkl. des geplanten. */
  countInWindow: number;
  limit: number;
  windowMonths: number;
  /** Datum, ab dem wieder ein Wurf möglich wäre. */
  freeFrom?: ISODate;
  message: string;
}

/**
 * Prüft die Verbandsregel „höchstens N Würfe je Königin in M Monaten".
 * Gezählt werden geborene Würfe; der geplante zählt mit.
 */
export function checkLitterPause(
  existingBirthDates: ISODate[],
  plannedDate: ISODate,
  limit: number,
  windowMonths: number,
): LitterPauseCheck {
  const windowDays = Math.round(windowMonths * 30.44);
  // Alle Würfe, die zum geplanten Zeitpunkt noch im Fenster liegen.
  const inWindow = existingBirthDates
    .filter((d) => {
      const age = daysBetween(d, plannedDate);
      return age >= 0 && age < windowDays;
    })
    .sort();

  const countInWindow = inWindow.length + 1;
  const allowed = countInWindow <= limit;

  if (allowed) {
    return {
      allowed: true,
      countInWindow,
      limit,
      windowMonths,
      message:
        countInWindow === limit
          ? `Das wäre der ${countInWindow}. Wurf in ${windowMonths} Monaten — damit ist das Limit erreicht.`
          : `${countInWindow}. Wurf in ${windowMonths} Monaten (erlaubt: ${limit}).`,
    };
  }

  // Sobald der älteste Wurf aus dem Fenster fällt, ist wieder Platz.
  const oldestRelevant = inWindow[inWindow.length - limit];
  const freeFrom = oldestRelevant
    ? addDaysISO(oldestRelevant, windowDays)
    : undefined;

  return {
    allowed: false,
    countInWindow,
    limit,
    windowMonths,
    freeFrom,
    message: freeFrom
      ? `Das wären ${countInWindow} Würfe in ${windowMonths} Monaten — erlaubt sind ${limit}. Wieder möglich ab ${freeFrom}.`
      : `Das wären ${countInWindow} Würfe in ${windowMonths} Monaten — erlaubt sind ${limit}.`,
  };
}

function addDaysISO(d: ISODate, days: number): ISODate {
  const [y, m, day] = d.split('-').map(Number);
  const x = new Date(y, m - 1, day + days);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${x.getFullYear()}-${pad(x.getMonth() + 1)}-${pad(x.getDate())}`;
}
