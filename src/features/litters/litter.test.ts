describe('dueDateFromMating', () => {
  it('rechnet 65 Tage auf das Deckdatum', () => {
    expect(dueDateFromMating('2026-02-01')).toBe('2026-04-07');
  });

  it('überspringt die Sommerzeitumstellung ohne Tagesverlust', () => {
    // 29.03.2026 ist der Umstellungstag in Deutschland.
    expect(dueDateFromMating('2026-03-20', 20)).toBe('2026-04-09');
  });

  it('berücksichtigt den Schalttag', () => {
    expect(dueDateFromMating('2024-01-01')).toBe('2024-03-06');
    expect(dueDateFromMating('2025-01-01')).toBe('2025-03-07');
  });

  it('rechnet über den Jahreswechsel', () => {
    expect(dueDateFromMating('2026-12-01')).toBe('2027-02-04');
  });

  it('erlaubt eine abweichende Trächtigkeitsdauer', () => {
    expect(dueDateFromMating('2026-03-01', 63)).toBe('2026-05-03');
  });

  it('liefert nichts ohne Deckdatum', () => {
    expect(dueDateFromMating(undefined)).toBeUndefined();
    expect(dueDateFromMating(null)).toBeUndefined();
    expect(dueDateFromMating('2026-03-01', Number.NaN)).toBeUndefined();
  });
});

