describe('analyzeLitterWeights', () => {
  const thresholds = DEFAULT_SETTINGS.weight;

  function kw(id: string, over: Partial<WeighedKitten> = {}): WeighedKitten {
    return { id, stillborn: false, saleStatus: 'available', birthWeightG: 95, ...over };
  }

  it('bewertet gar nichts, wenn es keine Kitten gibt', () => {
    const map = analyzeLitterWeights([], [], thresholds, '2026-03-01', '2026-03-05');
    expect(map.size).toBe(0);
    expect(countWeightWarnings(map)).toBe(0);
  });

  it('lässt tote Kitten aus der Bewertung heraus', () => {
    const map = analyzeLitterWeights(
      [kw('a'), kw('tot', { stillborn: true, saleStatus: 'deceased' })],
      [],
      thresholds,
      '2026-03-01',
      '2026-03-05',
    );
    expect([...map.keys()]).toEqual(['a']);
  });

  it('meldet fehlende Wiegungen als unbekannt statt als Warnung', () => {
    const map = analyzeLitterWeights([kw('a')], [], thresholds, '2026-03-01', '2026-03-05');
    expect(map.get('a')?.level).toBe('unknown');
    expect(countWeightWarnings(map)).toBe(0);
  });

  it('erkennt ein Sorgenkind im Vergleich zu den Geschwistern', () => {
    const kittens = [kw('gut1'), kw('gut2'), kw('klein', { birthWeightG: 70 })];
    const weights = [
      { kittenId: 'gut1', at: at(2026, 3, 1, 8), grams: 95 },
      { kittenId: 'gut1', at: at(2026, 3, 5, 8), grams: 135 },
      { kittenId: 'gut2', at: at(2026, 3, 1, 8), grams: 96 },
      { kittenId: 'gut2', at: at(2026, 3, 5, 8), grams: 137 },
      { kittenId: 'klein', at: at(2026, 3, 1, 8), grams: 70 },
      { kittenId: 'klein', at: at(2026, 3, 5, 8), grams: 78 },
    ];
    const map = analyzeLitterWeights(kittens, weights, thresholds, '2026-03-01', '2026-03-05');
    expect(map.get('gut1')?.level).toBe('ok');
    expect(map.get('klein')?.level === 'concern' || map.get('klein')?.level === 'critical').toBe(
      true,
    );
    expect(countWeightWarnings(map)).toBe(1);
  });

  it('kommt mit Lücken und mehreren Messungen pro Tag zurecht', () => {
    const weights = [
      { kittenId: 'a', at: at(2026, 3, 1, 7), grams: 95 },
      { kittenId: 'a', at: at(2026, 3, 1, 19), grams: 99 },
      // Zwei Tage übersprungen.
      { kittenId: 'a', at: at(2026, 3, 4, 8), grams: 128 },
    ];
    const map = analyzeLitterWeights([kw('a')], weights, thresholds, '2026-03-01', '2026-03-04');
    expect(map.get('a')?.level).toBe('ok');
    expect(map.get('a')?.gainPerDay).toBeGreaterThan(7);
  });

  it('funktioniert auch ohne Geburtsdatum des Wurfes', () => {
    const weights = [
      { kittenId: 'a', at: at(2026, 3, 1, 8), grams: 95 },
      { kittenId: 'a', at: at(2026, 3, 3, 8), grams: 90 },
    ];
    const map = analyzeLitterWeights([kw('a')], weights, thresholds, undefined, '2026-03-03');
    expect(map.get('a')?.level).toBe('critical');
    expect(countWeightWarnings(map)).toBe(1);
  });
});

