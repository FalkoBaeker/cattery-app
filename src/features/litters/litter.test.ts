function k(
  id: string,
  over: Partial<Pick<Kitten, 'stillborn' | 'saleStatus' | 'sex'>> = {},
): KittenLike {
  return {
    id,
    stillborn: false,
    saleStatus: 'available' as KittenSaleStatus,
    sex: 'unknown' as SexOrUnknown,
    ...over,
  };
}

/** Zeitpunkt in *lokaler* Zeit — sonst hängt der Test an der Zeitzone. */
function at(y: number, m: number, d: number, h = 12, min = 0): string {
  return new Date(y, m - 1, d, h, min).toISOString();
}

function task(over: Partial<CareTask> & Pick<CareTask, 'dueDate'>): CareTask {
  return {
    id: over.dueDate + (over.title ?? ''),
    kind: 'custom',
    title: 'Aufgabe',
    autoGenerated: true,
    createdAt: at(2026, 1, 1),
    updatedAt: at(2026, 1, 1),
    ...over,
  };
}

