describe('contractionIntervals', () => {
  it('liefert für eine leere Liste nichts', () => {
    expect(contractionIntervals([])).toEqual([]);
  });

  it('lässt die erste Wehe ohne Abstand', () => {
    const list = contractionIntervals([{ kind: 'contraction', at: at(2026, 3, 1, 2, 0) }]);
    expect(list).toHaveLength(1);
    expect(list[0].secondsSincePrevious).toBeUndefined();
  });

  it('sortiert unsortierte Eingaben', () => {
    const list = contractionIntervals([
      { kind: 'contraction', at: at(2026, 3, 1, 2, 10) },
      { kind: 'contraction', at: at(2026, 3, 1, 2, 0) },
      { kind: 'contraction', at: at(2026, 3, 1, 2, 4) },
    ]);
    expect(list.map((e) => e.secondsSincePrevious)).toEqual([undefined, 240, 360]);
  });

  it('verkraftet gleiche Zeitstempel', () => {
    const t = at(2026, 3, 1, 2, 0);
    const list = contractionIntervals([
      { kind: 'contraction', at: t },
      { kind: 'contraction', at: t },
    ]);
    expect(list[1].secondsSincePrevious).toBe(0);
  });

  it('beachtet nur Wehen', () => {
    const list = contractionIntervals([
      { kind: 'note', at: at(2026, 3, 1, 1, 0) },
      { kind: 'contraction', at: at(2026, 3, 1, 2, 0) },
      { kind: 'kitten_born', at: at(2026, 3, 1, 2, 30) },
    ]);
    expect(list).toHaveLength(1);
  });

  it('wirft ungültige Zeitstempel weg', () => {
    const list = contractionIntervals([
      { kind: 'contraction', at: 'kaputt' },
      { kind: 'contraction', at: at(2026, 3, 1, 2, 0) },
    ]);
    expect(list).toHaveLength(1);
  });
});

describe('contractionStats', () => {
  function wehen(minutes: number[]) {
    let t = 0;
    return minutes.map((m) => {
      t += m;
      return { kind: 'contraction' as const, at: new Date(2026, 2, 1, 2, t).toISOString() };
    });
  }

  it('bleibt bei einer einzelnen Wehe unbestimmt', () => {
    const s = contractionStats(wehen([0]));
    expect(s.count).toBe(1);
    expect(s.trend).toBe('unknown');
    expect(s.averageSeconds).toBeUndefined();
  });

  it('erkennt kürzer werdende Abstände', () => {
    const s = contractionStats(wehen([0, 10, 10, 2]));
    expect(s.trend).toBe('shorter');
    expect(s.intervalsSeconds).toEqual([600, 600, 120]);
  });

  it('erkennt länger werdende Abstände', () => {
    const s = contractionStats(wehen([0, 2, 2, 20]));
    expect(s.trend).toBe('longer');
  });

  it('erkennt gleichbleibende Abstände', () => {
    const s = contractionStats(wehen([0, 5, 5, 5]));
    expect(s.trend).toBe('steady');
    expect(s.averageSeconds).toBe(300);
  });

  it('zeigt nur die jüngsten Abstände, jüngster zuerst', () => {
    const s = contractionStats(wehen([0, 1, 2, 3, 4, 5, 6]), 3);
    expect(s.recentSeconds).toEqual([360, 300, 240]);
  });
});

