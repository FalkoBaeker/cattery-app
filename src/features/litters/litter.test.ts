describe('summarizeLitter', () => {
  it('meldet einen leeren Wurf sauber', () => {
    const s = summarizeLitter([], [], '2026-03-01');
    expect(s.isEmpty).toBe(true);
    expect(s.alive).toBe(0);
    expect(s.allWeighedToday).toBe(false);
    expect(summaryLine(s)).toBe('Noch keine Kitten erfasst');
    expect(weighingLine(s)).toBe('Nichts zu wiegen');
  });

  it('zählt ein einzelnes Kitten', () => {
    const s = summarizeLitter([k('a', { sex: 'female' })], [], '2026-03-01');
    expect(s.alive).toBe(1);
    expect(s.females).toBe(1);
    expect(summaryLine(s)).toBe('1 Kitten · 1 Katze');
    expect(weighingLine(s)).toBe('Heute noch nicht gewogen (1)');
  });

  it('zählt neun Kitten mit gemischten Zuständen', () => {
    const kittens = [
      k('1', { sex: 'female' }),
      k('2', { sex: 'female', saleStatus: 'reserved' }),
      k('3', { sex: 'male', saleStatus: 'sold' }),
      k('4', { sex: 'male', saleStatus: 'sold_breeding_reserved' }),
      k('5', { sex: 'male', saleStatus: 'kept' }),
      k('6', { sex: 'unknown' }),
      k('7', { sex: 'female' }),
      k('8', { stillborn: true, saleStatus: 'deceased' }),
      k('9', { saleStatus: 'deceased' }),
    ];
    const s = summarizeLitter(kittens, [], '2026-03-01');
    expect(s.total).toBe(9);
    expect(s.alive).toBe(7);
    expect(s.stillborn).toBe(1);
    expect(s.deceased).toBe(1);
    expect(s.females).toBe(3);
    expect(s.males).toBe(3);
    expect(s.unknownSex).toBe(1);
    expect(s.sold).toBe(2);
    expect(s.reserved).toBe(1);
    expect(s.available).toBe(3);
    expect(s.kept).toBe(1);
    expect(summaryLine(s)).toContain('1 Totgeburt');
    expect(summaryLine(s)).toContain('1 verstorben');
  });

  it('zählt mehrere Wiegungen desselben Tages nur einmal', () => {
    const kittens = [k('a'), k('b')];
    const weights = [
      { kittenId: 'a', at: at(2026, 3, 1, 7) },
      { kittenId: 'a', at: at(2026, 3, 1, 19) },
    ];
    const s = summarizeLitter(kittens, weights, '2026-03-01');
    expect(s.weighedToday).toBe(1);
    expect(s.allWeighedToday).toBe(false);
    expect(weighingLine(s)).toBe('1 von 2 heute gewogen');
  });

  it('ignoriert Wiegungen anderer Tage und toter Kitten', () => {
    const kittens = [k('a'), k('tot', { stillborn: true, saleStatus: 'deceased' })];
    const weights = [
      { kittenId: 'a', at: at(2026, 2, 28, 20) },
      { kittenId: 'tot', at: at(2026, 3, 1, 8) },
    ];
    const s = summarizeLitter(kittens, weights, '2026-03-01');
    expect(s.weighedToday).toBe(0);
    expect(s.toWeigh).toBe(1);
  });

  it('erkennt einen vollständig gewogenen Wurf', () => {
    const kittens = [k('a'), k('b')];
    const weights = [
      { kittenId: 'a', at: at(2026, 3, 1, 7) },
      { kittenId: 'b', at: at(2026, 3, 1, 8) },
    ];
    const s = summarizeLitter(kittens, weights, '2026-03-01');
    expect(s.allWeighedToday).toBe(true);
    expect(weighingLine(s)).toBe('Heute alle gewogen');
  });

  it('erkennt einen Wurf, in dem nur noch tote Kitten stehen', () => {
    const s = summarizeLitter([k('a', { stillborn: true, saleStatus: 'deceased' })], [], '2026-03-01');
    expect(s.alive).toBe(0);
    expect(s.allWeighedToday).toBe(false);
    expect(weighingLine(s)).toBe('Nichts zu wiegen');
  });
});

describe('weighingStatus', () => {
  const ref = '2026-03-10';

  it('mahnt in der Wiegephase, wenn heute noch keiner gewogen wurde', () => {
    const s = summarizeLitter([k('a'), k('b')], [], ref);
    // Geburt vor 2 Wochen — mitten in der Wiegephase.
    const status = weighingStatus(s, '2026-02-24', ref);
    expect(status?.tone).toBe('warn');
    expect(status?.text).toBe('Heute noch nicht gewogen (2)');
  });

  it('lobt, wenn heute alle gewogen sind', () => {
    const s = summarizeLitter(
      [k('a')],
      [{ kittenId: 'a', at: '2026-03-10T08:00:00.000Z' }],
      ref,
    );
    const status = weighingStatus(s, '2026-02-24', ref);
    expect(status?.tone).toBe('ok');
    expect(status?.text).toBe('Heute alle gewogen');
  });

  it('erklärt ab Woche 5 neutral, warum nicht mehr gewogen wird', () => {
    const s = summarizeLitter([k('a')], [], ref);
    // Geburt vor 6 Wochen — Wiegephase vorbei, aber kein wortloses Verschwinden.
    const status = weighingStatus(s, '2026-01-27', ref);
    expect(status?.tone).toBe('neutral');
    expect(status?.text).toBe('Ab Woche 5 kein Routinewiegen mehr');
  });

  it('schweigt ohne Kitten oder ohne Geburtsdatum', () => {
    expect(weighingStatus(summarizeLitter([], [], ref), '2026-02-24', ref)).toBeUndefined();
    expect(weighingStatus(summarizeLitter([k('a')], [], ref), undefined, ref)).toBeUndefined();
  });
});

