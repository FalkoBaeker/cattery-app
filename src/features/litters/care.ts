import { db, insert, patch } from '../../db/db';
import { dateOf, todayISO } from '../../lib/date';
import { isValidISODate } from '../cats/heat';
import type { CareTask, CareTaskKind, ID, Kitten } from '../../types';
import { newId } from '../../lib/id';

export const INDIVIDUAL_CARE_KINDS: CareTaskKind[] = ['vaccination', 'deworming', 'chip', 'neuter', 'health_test'];

export function careDateForKitten(task: CareTask, kittenId: ID): string | undefined {
  return task.completedKittenDates ? task.completedKittenDates[kittenId] : task.doneAt;
}

function living(k: Kitten): boolean {
  return !k.stillborn && !k.diedAt && k.saleStatus !== 'deceased';
}

export async function saveCareCompletion(taskId: ID, date: string | undefined, selectedIds: ID[]): Promise<void> {
  if (date !== undefined && (!isValidISODate(date) || date > todayISO())) {
    throw new Error('Bitte ein gültiges Datum bis heute wählen.');
  }
  await db.transaction('rw', db.careTasks, db.kittens, db.litters, db.cats, async () => {
    const task = await db.careTasks.get(taskId);
    if (!task) throw new Error('Der Eintrag existiert nicht mehr.');
    const litter = task.litterId ? await db.litters.get(task.litterId) : undefined;
    const kittens = task.litterId ? await db.kittens.where('litterId').equals(task.litterId).toArray() : [];
    const targets = kittens.filter((kitten) => selectedIds.includes(kitten.id));
    if (INDIVIDUAL_CARE_KINDS.includes(task.kind) && task.litterId) {
      if (!targets.length || targets.length !== new Set(selectedIds).size) throw new Error('Bitte mindestens ein Tier wählen.');
      for (const kitten of targets) {
        const birth = kitten.bornAt ? dateOf(kitten.bornAt) : litter?.birthDate;
        if (date && birth && date < birth) throw new Error('Das Datum liegt vor der Geburt eines ausgewählten Tiers.');
        if (date && kitten.diedAt && date > kitten.diedAt) throw new Error('Das Datum liegt nach dem Versterben eines ausgewählten Tiers.');
      }
      if (task.kittenId) {
        const siblings = await db.careTasks.where('litterId').equals(task.litterId).toArray();
        for (const kitten of targets) {
          const related = kitten.id === task.kittenId ? task : siblings.find((item) => item.kittenId === kitten.id && item.kind === task.kind && (task.autoGenerated ? item.autoGenerated && task.kind === 'neuter' : item.planKey === task.planKey));
          if (related) await patch(db.careTasks, related.id, { doneAt: date });
          else if (date) await insert(db.careTasks, {
            kind: task.kind, title: task.title, litterId: task.litterId, kittenId: kitten.id,
            dueDate: date, doneAt: date, autoGenerated: false,
          });
        }
      } else {
        const dates = { ...task.completedKittenDates };
        // A legacy group completion applied to the whole litter.
        if (!task.completedKittenDates && task.doneAt) for (const kitten of kittens.filter(living)) dates[kitten.id] = task.doneAt;
        for (const id of selectedIds) {
          if (date) dates[id] = date;
          else delete dates[id];
        }
        const eligible = kittens.filter(living);
        const allDone = eligible.length > 0 && eligible.every((kitten) => Boolean(dates[kitten.id]));
        const doneAt = allDone ? eligible.map((kitten) => dates[kitten.id]).sort().at(-1) : undefined;
        await patch(db.careTasks, task.id, { completedKittenDates: dates, doneAt });
      }
    } else {
      if (date && litter?.birthDate && date < litter.birthDate) throw new Error('Das Datum liegt vor der Geburt.');
      if (task.catId) {
        const cat = await db.cats.get(task.catId);
        if (date && cat?.birthDate && date < cat.birthDate) throw new Error('Das Datum liegt vor der Geburt.');
        if (task.kind === 'neuter' && date) await patch(db.cats, task.catId, { status: 'neutered' });
      }
      await patch(db.careTasks, task.id, { doneAt: date });
    }
  });
}

export async function createCareRecord(input: {
  kind: CareTaskKind; title: string; date: string; litterId?: ID; catId?: ID; kittenIds?: ID[];
}): Promise<void> {
  await db.transaction('rw', db.careTasks, db.kittens, db.litters, db.cats, async () => {
    const selectedIds = [...new Set(input.kittenIds ?? [])];
    if (input.litterId && INDIVIDUAL_CARE_KINDS.includes(input.kind) && !selectedIds.length) throw new Error('Bitte mindestens ein Tier wählen.');
    const planKey = `record:${newId()}`;
    const targets = input.litterId && INDIVIDUAL_CARE_KINDS.includes(input.kind) ? selectedIds : [undefined];
    for (const kittenId of targets) {
      const task = await insert(db.careTasks, {
        kind: input.kind, title: input.title, dueDate: input.date,
        litterId: input.litterId, catId: input.catId, kittenId, autoGenerated: false, planKey,
      });
      await saveCareCompletion(task.id, input.date, kittenId ? [kittenId] : []);
    }
  });
}
