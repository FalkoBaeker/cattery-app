import { useState } from 'react';
import { Button, EventDateField, Select, Sheet, Stack, TextInput, useToast } from '../../ui';
import { CARE_TASK_LABEL, kittenLabel, type CareTask, type CareTaskKind, type Cat, type Kitten, type Litter } from '../../types';
import { formatDate, todayISO } from '../../lib/date';
import { careDateForKitten, createCareRecord, INDIVIDUAL_CARE_KINDS, saveCareCompletion } from './care';

export function CareTaskSheet({ task, tasks = [], litter, kittens = [], cat, defaultKittenId, onClose }: {
  task?: CareTask;
  tasks?: CareTask[];
  litter?: Litter;
  kittens?: Kitten[];
  cat?: Cat;
  defaultKittenId?: string;
  onClose: () => void;
}) {
  const toast = useToast();
  const [kind, setKind] = useState<CareTaskKind>(task?.kind ?? 'vaccination');
  const [date, setDate] = useState((defaultKittenId && task ? careDateForKitten(task, defaultKittenId) : task?.doneAt) ?? todayISO());
  const candidates = kittens.filter((kitten) => (!kitten.stillborn || kitten.id === task?.kittenId) && (!kitten.diedAt || date <= kitten.diedAt));
  const [title, setTitle] = useState(task?.title ?? '');
  const [selected, setSelected] = useState<string[]>(task?.kittenId ? [task.kittenId] : defaultKittenId ? [defaultKittenId] : candidates.map((kitten) => kitten.id));
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string>();
  const individual = Boolean(litter && INDIVIDUAL_CARE_KINDS.includes(kind));
  const completionFor = (id: string) => task?.kittenId
    ? tasks.find((item) => item.kittenId === id && item.kind === task.kind && (task.autoGenerated ? item.autoGenerated && task.kind === 'neuter' : item.planKey === task.planKey))?.doneAt ?? (task.kittenId === id ? task.doneAt : undefined)
    : task ? careDateForKitten(task, id) : undefined;
  const canClear = task && (task.doneAt || selected.some((id) => Boolean(completionFor(id))));

  async function save(clear = false) {
    setSaving(true);
    setError(undefined);
    try {
      if (task) await saveCareCompletion(task.id, clear ? undefined : date, selected);
      else await createCareRecord({ kind, title: title.trim() || CARE_TASK_LABEL[kind], date, litterId: litter?.id, catId: cat?.id, kittenIds: selected });
      toast.success(clear ? 'Erledigung aufgehoben.' : 'Ereignis gespeichert.');
      onClose();
    } catch (failure) {
      setError(failure instanceof Error ? failure.message : 'Speichern fehlgeschlagen. Die Eingabe bleibt erhalten.');
    } finally {
      setSaving(false);
    }
  }

  return (
    <Sheet open onClose={onClose} title={task?.title ?? 'Ereignis eintragen'} footer={
      <div className="flex flex-col gap-2">
        <Button block variant="primary" icon="check" loading={saving} onClick={() => void save()}>Speichern</Button>
        {canClear && <Button block variant="ghost" disabled={saving} onClick={() => void save(true)}>Erledigung für Auswahl aufheben</Button>}
      </div>
    }>
      <Stack>
        {!task && <Select label="Ereignis" value={kind} onChange={(event) => setKind(event.target.value as CareTaskKind)} options={[...INDIVIDUAL_CARE_KINDS, 'custom' as const].map((value) => ({ value, label: CARE_TASK_LABEL[value] }))} />}
        {!task && kind === 'custom' && <TextInput label="Bezeichnung" value={title} onChange={(event) => setTitle(event.target.value)} />}
        <EventDateField label="Erledigt am" value={date} onChange={setDate} max={todayISO()} required error={error} disabled={saving} />
        {individual && <fieldset className="flex min-w-0 flex-col gap-2">
          <legend className="mb-2 text-sm font-medium text-text-dim">Tiere</legend>
          <label className="flex min-h-11 items-center gap-3 border-b border-border pb-2 text-sm font-semibold">
            <input type="checkbox" checked={candidates.length > 0 && selected.length === candidates.length} disabled={saving} onChange={(event) => setSelected(event.target.checked ? candidates.map((kitten) => kitten.id) : [])} className="size-5 accent-accent" /> Ganzer Wurf
          </label>
          {candidates.map((kitten) => {
            const doneDate = completionFor(kitten.id);
            return <label key={kitten.id} className="flex min-h-12 items-center gap-3 py-2">
              <input type="checkbox" checked={selected.includes(kitten.id)} disabled={saving} onChange={(event) => {
                setSelected((ids) => event.target.checked ? [...ids, kitten.id] : ids.filter((id) => id !== kitten.id));
              }} className="size-5 shrink-0 accent-accent" />
              <span className="min-w-0 flex-1 text-sm">{kittenLabel(kitten)}</span>
              {doneDate && <span className="text-xs text-text-dim">{formatDate(doneDate)}</span>}
            </label>;
          })}
        </fieldset>}
      </Stack>
    </Sheet>
  );
}
