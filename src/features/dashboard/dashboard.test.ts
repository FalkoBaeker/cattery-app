describe('weighPhase', () => {
  it('wiegt in den ersten zwei Wochen täglich', () => {
    expect(weighPhase(0)).toBe('daily');
    expect(weighPhase(13)).toBe('daily');
  });

  it('wechselt in Woche 3 auf alle zwei Tage', () => {
    expect(weighPhase(14)).toBe('every2days');
    expect(weighPhase(27)).toBe('every2days');
  });

  it('hört ab Woche 5 auf', () => {
    expect(weighPhase(28)).toBe('none');
    expect(weighPhase(400)).toBe('none');
  });

  it('verträgt Unsinn', () => {
    expect(weighPhase(-3)).toBe('none');
    expect(weighPhase(Number.NaN)).toBe('none');
  });
});

describe('litterName', () => {
  it('benennt den Wurf nach der Mutter', () => {
    const cats = new Map([['cat-1', cat()]]);
    expect(litterName(litter(), cats)).toBe('Wurf von Mira');
  });

  it('weicht auf das Geburtsdatum aus, wenn die Mutter fehlt', () => {
    expect(litterName(litter(), new Map())).toBe('Wurf vom 01.03.2026');
  });

  it('bleibt schlicht, wenn weder Mutter noch Geburtsdatum bekannt sind', () => {
    expect(litterName(litter({ birthDate: undefined }), new Map())).toBe('Wurf');
  });

  it('verkraftet sehr lange Namen unverändert', () => {
    const long = 'Anastasia Wolkonskaja von der Silbernen Newa am Roten Platz';
    const cats = new Map([['cat-1', cat({ callName: long })]]);
    expect(litterName(litter(), cats)).toBe(`Wurf von ${long}`);
  });
});

