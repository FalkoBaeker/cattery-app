describe('backupStatus', () => {
  it('ist ohne Daten nie fällig', () => {
    expect(backupStatus(undefined, 14, '2026-03-10', false).due).toBe(false);
  });

  it('ist fällig, wenn noch nie gesichert wurde und Daten da sind', () => {
    const s = backupStatus(undefined, 14, '2026-03-10', true);
    expect(s.due).toBe(true);
    expect(s.neverBackedUp).toBe(true);
    expect(s.daysSince).toBeUndefined();
  });

  it('wird nach Ablauf des Intervalls fällig', () => {
    const last = new Date(2026, 1, 24, 12).toISOString(); // 24.02.2026
    expect(backupStatus(last, 14, '2026-03-09', true).due).toBe(false);
    expect(backupStatus(last, 14, '2026-03-10', true).due).toBe(true);
    expect(backupStatus(last, 14, '2026-03-10', true).daysSince).toBe(14);
  });

  it('fängt ein unsinniges Intervall ab', () => {
    expect(backupStatus(undefined, 0, '2026-03-10', true).intervalDays).toBe(14);
    expect(backupStatus(undefined, Number.NaN, '2026-03-10', true).intervalDays).toBe(14);
  });

  it('rechnet über den Sommerzeitwechsel richtig', () => {
    const last = new Date(2026, 2, 22, 23).toISOString(); // 22.03.2026
    expect(backupStatus(last, 7, '2026-03-29', true).daysSince).toBe(7);
  });
});

