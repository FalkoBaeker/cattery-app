import { beforeEach, describe, expect, it } from 'vitest';

import { db, insert, insertPlain, putAttachment, wipeDatabase } from '../../db/db';
import { CatHasLittersError, deleteCatWithReferences } from './store';

beforeEach(async () => {
  await wipeDatabase();
});

describe('Katze löschen', () => {
  it('löscht operative Daten und bewahrt Historie ohne tote Verweise', async () => {
    const photo = await putAttachment(new Blob(['foto'], { type: 'image/jpeg' }));
    const pdf = await putAttachment(new Blob(['pdf'], { type: 'application/pdf' }));
    const cat = await insert(db.cats, {
      callName: 'Mascha',
      sex: 'female',
      breed: 'Russisch Blau',
      status: 'active',
      isOwn: true,
      photoAttachmentId: photo.id,
    });
    await insert(db.heatCycles, { catId: cat.id, startDate: '2026-01-01' });
    await insert(db.healthTests, {
      catId: cat.id,
      kind: 'hcm',
      date: '2026-01-02',
    });
    await insertPlain(db.catWeights, {
      catId: cat.id,
      at: '2026-01-03T12:00:00.000Z',
      grams: 3_900,
    });
    await insert(db.careTasks, {
      kind: 'health_test',
      title: 'HCM kontrollieren',
      dueDate: '2026-07-01',
      catId: cat.id,
      autoGenerated: false,
    });
    const appointment = await insert(db.appointments, {
      kind: 'vet',
      startAt: '2026-02-01T10:00:00.000Z',
      catId: cat.id,
      remind24h: false,
      remind1h: false,
    });
    const document = await insert(db.documents, {
      kind: 'health_test',
      title: 'HCM-Befund',
      catId: cat.id,
      pageIds: [],
      customerVisible: false,
    });
    const cost = await insert(db.costs, {
      date: '2026-02-01',
      category: 'vet',
      amountCents: 15_000,
      catId: cat.id,
    });
    const contract = await insert(db.contracts, {
      type: 'standard',
      data: {
        type: 'standard',
        buyers: [{ name: 'Familie Muster' }],
        animals: [{ catId: cat.id, name: 'Mascha', sex: 'female' }],
        breed: 'Russisch Blau',
      },
      pdfAttachmentId: pdf.id,
    });
    const breedingUse = await insert(db.breedingUses, {
      contractId: contract.id,
      catId: cat.id,
      catName: 'Mascha',
      startDate: '2026-03-01',
      months: 18,
      extensionMonths: 6,
      deadlineDate: '2027-09-01',
      stage: 'at_buyer',
      history: [],
    });

    await deleteCatWithReferences(cat);

    expect(await db.cats.get(cat.id)).toBeUndefined();
    expect(await db.heatCycles.where('catId').equals(cat.id).count()).toBe(0);
    expect(await db.healthTests.where('catId').equals(cat.id).count()).toBe(0);
    expect(await db.catWeights.where('catId').equals(cat.id).count()).toBe(0);
    expect(await db.careTasks.where('catId').equals(cat.id).count()).toBe(0);
    expect(await db.attachments.get(photo.id)).toBeUndefined();

    expect((await db.appointments.get(appointment.id))?.catId).toBeUndefined();
    expect((await db.documents.get(document.id))?.catId).toBeUndefined();
    expect((await db.costs.get(cost.id))?.catId).toBeUndefined();
    expect((await db.breedingUses.get(breedingUse.id))?.catId).toBeUndefined();
    expect((await db.breedingUses.get(breedingUse.id))?.catName).toBe('Mascha');
    expect((await db.contracts.get(contract.id))?.data.animals[0]).toEqual({
      catId: undefined,
      name: 'Mascha',
      sex: 'female',
    });
    // catId ist keine druckbare Vertragsangabe: PDF und Vertragshistorie
    // bleiben daher bewusst erhalten.
    expect((await db.contracts.get(contract.id))?.pdfAttachmentId).toBe(pdf.id);
    expect(await db.attachments.get(pdf.id)).toBeDefined();
  });

  it('bricht atomar ab, solange das Tier noch an einem Wurf hängt', async () => {
    const cat = await insert(db.cats, {
      callName: 'Mascha',
      sex: 'female',
      breed: 'Russisch Blau',
      status: 'active',
      isOwn: true,
    });
    await insert(db.litters, {
      motherId: cat.id,
      status: 'planned',
    });
    await insert(db.heatCycles, { catId: cat.id, startDate: '2026-01-01' });

    await expect(deleteCatWithReferences(cat)).rejects.toEqual(
      expect.objectContaining<Partial<CatHasLittersError>>({
        name: 'CatHasLittersError',
        litterCount: 1,
      }),
    );
    expect(await db.cats.get(cat.id)).toBeDefined();
    expect(await db.heatCycles.where('catId').equals(cat.id).count()).toBe(1);
  });
});
