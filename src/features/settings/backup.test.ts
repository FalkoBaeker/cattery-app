describe('Base64-Umwandlung', () => {
  it('läuft für einfachen Text hin und zurück', () => {
    const bytes = new TextEncoder().encode('Grüße aus der Zuchtstube');
    const back = base64ToBytes(bytesToBase64(bytes));
    expect(new TextDecoder().decode(back)).toBe('Grüße aus der Zuchtstube');
  });

  it('verträgt leere Daten', () => {
    expect(bytesToBase64(new Uint8Array(0))).toBe('');
    expect(base64ToBytes('').length).toBe(0);
  });

  it('verträgt große Datenmengen ohne Stapelüberlauf', () => {
    const bytes = new Uint8Array(300_000);
    for (let i = 0; i < bytes.length; i++) bytes[i] = i % 256;
    const back = base64ToBytes(bytesToBase64(bytes));
    expect(back.length).toBe(bytes.length);
    expect(back[0]).toBe(0);
    expect(back[255]).toBe(255);
    expect(back[299_999]).toBe(299_999 % 256);
  });
});

describe('Anhänge', () => {
  it('wandelt einen Anhang hin und zurück', async () => {
    const original: Attachment = {
      id: 'att-x',
      blob: storableBlob('Impfpass Seite 1', 'image/jpeg'),
      mime: 'image/jpeg',
      bytes: 16,
      width: 800,
      height: 600,
      createdAt: '2026-01-01T00:00:00.000Z',
    };
    const encoded = await encodeAttachment(original);
    expect(encoded.data.length).toBeGreaterThan(0);
    expect(encoded.width).toBe(800);

    const decoded = decodeAttachment(encoded);
    expect(decoded.id).toBe('att-x');
    expect(decoded.mime).toBe('image/jpeg');
    expect(decoded.bytes).toBe(encoded.bytes);
    const text = new TextDecoder().decode(base64ToBytes(encoded.data));
    expect(text).toBe('Impfpass Seite 1');
  });

  it('setzt eine sinnvolle Vorgabe, wenn die Art fehlt', () => {
    const decoded = decodeAttachment({
      id: 'a',
      mime: '',
      bytes: 0,
      createdAt: '2026-01-01T00:00:00.000Z',
      data: '',
    });
    expect(decoded.mime).toBe('application/octet-stream');
    expect(decoded.bytes).toBe(0);
  });
});

describe('Sicherung über alle Tabellen', () => {
  it('sichert und stellt vollständig wieder her (Rundlauf)', async () => {
    await fillDatabase();

    const steps: string[] = [];
    const file = await createBackup((p) => steps.push(`${p.phase}:${p.done}/${p.total}`));

    expect(file.format).toBe(BACKUP_FORMAT);
    expect(file.version).toBe(BACKUP_VERSION);
    expect(steps.length).toBeGreaterThan(BACKUP_TABLE_NAMES.length);

    // Jede Tabelle hat genau einen Datensatz.
    for (const name of BACKUP_TABLE_NAMES) {
      expect(file.tables[name], `Tabelle ${name}`).toHaveLength(1);
    }
    expect(file.attachments).toHaveLength(1);
    expect(new TextDecoder().decode(base64ToBytes(file.attachments[0].data))).toBe('Seite eins');

    // Über die Datei gehen, wie es die echte Wiederherstellung tut.
    const text = serializeBackup(file);
    const parsed = parseBackup(text);
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;

    await wipeDatabase();
    expect(await db.cats.count()).toBe(0);

    const restoreSteps: string[] = [];
    await restoreBackup(parsed.file, (p) => restoreSteps.push(p.phase));
    expect(restoreSteps[restoreSteps.length - 1]).toBe('done');

    for (const name of BACKUP_TABLE_NAMES) {
      expect(await db.table(name).count(), `Tabelle ${name}`).toBe(1);
    }
    expect(await db.attachments.count()).toBe(1);

    const cat = await db.cats.get('cat-1');
    expect(cat?.callName).toBe('Mira');
    const kittenBack = await db.kittens.get('kit-1');
    expect(kittenBack?.birthWeightG).toBe(94);
    const costBack = await db.costs.get('cost-1');
    expect(costBack?.amountCents).toBe(12_000);
    const settingsBack = await db.settings.get('singleton');
    expect(settingsBack?.gestationDays).toBe(65);
    const attBack = await db.attachments.get('att-1');
    expect(attBack?.mime).toBe('text/plain');
    expect(attBack?.bytes).toBe(10);
  });

  it('sichert und stellt eine völlig leere Datenbank wieder her', async () => {
    const file = await createBackup();
    expect(backupItemCount(file)).toBe(0);
    expect(summarizeBackup(file)).toEqual([]);

    const parsed = parseBackup(serializeBackup(file));
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;

    await expect(restoreBackup(parsed.file)).resolves.toBeUndefined();
    expect(await db.cats.count()).toBe(0);
  });

  it('ersetzt vorhandene Daten vollständig', async () => {
    await fillDatabase();
    const file = await createBackup();

    // Zwischendurch etwas anderes anlegen …
    await wipeDatabase();
    await db.cats.put({
      id: 'cat-fremd',
      callName: 'Fremdes Tier',
      sex: 'male',
      breed: 'Russisch Blau',
      status: 'active',
      isOwn: true,
      ...STAMP,
    });

    await restoreBackup(file);

    expect(await db.cats.get('cat-fremd')).toBeUndefined();
    expect(await db.cats.get('cat-1')).toBeTruthy();
    expect(await db.cats.count()).toBe(1);
  });

  it('zählt den Inhalt für die Rückfrage auf', async () => {
    await fillDatabase();
    const file = await createBackup();
    const rows = summarizeBackup(file);
    const labels = rows.map((r) => r.label);
    expect(labels).toContain('Zuchttiere');
    expect(labels).toContain('Kitten');
    expect(labels).toContain('Anhänge (Fotos, PDFs)');
    // Einstellungen und Erinnerungs-Protokoll sind kein Zählwert für Menschen.
    expect(labels).not.toContain('Einstellungen');
    expect(labels).not.toContain('Erinnerungs-Protokoll');
    expect(rows.every((r) => r.count > 0)).toBe(true);
  });
});

describe('parseBackup — beschädigte und fremde Dateien', () => {
  it('erkennt kaputtes JSON', () => {
    const result = parseBackup('{ das ist kein json ');
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error).toMatch(/beschädigt/);
  });

  it('erkennt eine leere Datei', () => {
    expect(parseBackup('').ok).toBe(false);
  });

  it('lehnt eine fremde JSON-Datei ab', () => {
    const result = parseBackup(JSON.stringify({ hallo: 'welt' }));
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error).toBe('Das ist keine Sicherung dieser App.');
  });

  it('lehnt ein reines Array ab', () => {
    const result = parseBackup('[1,2,3]');
    expect(result.ok).toBe(false);
  });

  it('lehnt eine neuere Version ab und nennt die Nummer', () => {
    const result = parseBackup(
      JSON.stringify({ format: BACKUP_FORMAT, version: 99, tables: {}, attachments: [] }),
    );
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error).toMatch(/Version 99/);
    expect(result.error).toMatch(/aktualisieren/);
  });

  it('lehnt eine fehlende Version ab', () => {
    const result = parseBackup(JSON.stringify({ format: BACKUP_FORMAT, tables: {} }));
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error).toMatch(/Versionsangabe/);
  });

  it('lehnt fehlende Daten ab', () => {
    const result = parseBackup(JSON.stringify({ format: BACKUP_FORMAT, version: 1 }));
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error).toBe('In der Datei fehlen die Daten.');
  });

  it('lehnt einen beschädigten Abschnitt ab und benennt ihn deutsch', () => {
    const result = parseBackup(
      JSON.stringify({
        format: BACKUP_FORMAT,
        version: 1,
        tables: { cats: 'kaputt' },
        attachments: [],
      }),
    );
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error).toContain('Zuchttiere');
  });

  it('lehnt einen beschädigten Anhang-Abschnitt ab', () => {
    const result = parseBackup(
      JSON.stringify({ format: BACKUP_FORMAT, version: 1, tables: {}, attachments: 42 }),
    );
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error).toContain('Anhänge');
  });

  it('ergänzt fehlende Tabellen einer älteren Sicherung als leer', () => {
    const result = parseBackup(
      JSON.stringify({
        format: BACKUP_FORMAT,
        version: 1,
        createdAt: '2026-05-01T10:00:00.000Z',
        tables: { cats: [] },
      }),
    );
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    for (const name of BACKUP_TABLE_NAMES) {
      expect(Array.isArray(result.file.tables[name])).toBe(true);
    }
    expect(result.file.attachments).toEqual([]);
    expect(result.file.createdAt).toBe('2026-05-01T10:00:00.000Z');
  });

  it('wirft halbe Anhänge weg, statt daran zu scheitern', () => {
    const result = parseBackup(
      JSON.stringify({
        format: BACKUP_FORMAT,
        version: 1,
        tables: {},
        attachments: [{ id: 'gut', data: '' }, { id: 'ohne-daten' }, null, 'unsinn'],
      }),
    );
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.file.attachments).toHaveLength(1);
    expect(result.file.attachments[0].id).toBe('gut');
  });
});

describe('Dateiname und Größe', () => {
  it('baut einen sprechenden Dateinamen aus dem Datum', () => {
    expect(backupFileName(new Date(2026, 6, 31, 12))).toBe('cattery-sicherung-2026-07-31.json');
  });

  it('füllt einstellige Monate und Tage auf', () => {
    expect(backupFileName(new Date(2026, 0, 5, 12))).toBe('cattery-sicherung-2026-01-05.json');
  });

  it('misst die Größe in Byte, nicht in Zeichen', () => {
    expect(backupByteSize('äöü')).toBe(6);
    expect(backupByteSize('')).toBe(0);
  });
});

describe('backupItemCount', () => {
  it('zählt alle Datensätze samt Anhängen', () => {
    const file = {
      format: BACKUP_FORMAT,
      version: 1,
      createdAt: '2026-01-01T00:00:00.000Z',
      tables: Object.fromEntries(
        BACKUP_TABLE_NAMES.map((n) => [n, [] as unknown[]]),
      ) as unknown as BackupFile['tables'],
      attachments: [],
    } satisfies BackupFile;
    file.tables.cats = [{}, {}];
    file.tables.kittens = [{}];
    expect(backupItemCount(file)).toBe(3);
  });
});
