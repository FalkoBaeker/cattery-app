/**
 * jsdom-Blobs überstehen den strukturierten Klon von fake-indexeddb nicht.
 * Für Datenbanktests deshalb den Blob aus Node — im echten Safari ist es
 * derselbe Blob wie überall.
 */
function storableBlob(text: string, type = 'text/plain'): Blob {
  return new NodeBlob([text], { type }) as unknown as Blob;
}

