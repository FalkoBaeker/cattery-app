describe('dueReminders', () => {
  it('liefert bei leerer Liste nichts', () => {
    expect(dueReminders([], '2026-03-10T12:00:00Z')).toEqual({ notify: [], markFired: [] });
  });

  it('meldet nichts, solange der Termin weiter als 24 Stunden weg ist', () => {
    const check = dueReminders([appt()], '2026-03-09T12:59:00Z');
    expect(check.notify).toHaveLength(0);
    expect(check.markFired).toHaveLength(0);
  });

  it('meldet die 24-Stunden-Erinnerung ab genau 24 Stunden vorher', () => {
    const check = dueReminders([appt()], '2026-03-09T13:00:00Z');
    expect(check.notify).toHaveLength(1);
    expect(check.notify[0].kind).toBe('24h');
    expect(check.markFired).toEqual(['appt:a1:24h']);
  });

  it('meldet bei 23,9 Stunden Vorlauf die 24-Stunden-Erinnerung', () => {
    // 23,9 h vor 13:00Z = 13:06Z am Vortag.
    const check = dueReminders([appt()], '2026-03-09T13:06:00Z');
    expect(check.notify.map((r) => r.kind)).toEqual(['24h']);
  });

  it('meldet die 1-Stunden-Erinnerung, wenn die 24-Stunden-Erinnerung schon lief', () => {
    const check = dueReminders([appt()], '2026-03-10T12:30:00Z', ['appt:a1:24h']);
    expect(check.notify).toHaveLength(1);
    expect(check.notify[0].kind).toBe('1h');
    expect(check.markFired).toEqual(['appt:a1:1h']);
  });

  it('zeigt bei zwei gleichzeitig fälligen nur die dringendere, vermerkt aber beide', () => {
    // App wird erst 30 Minuten vor dem Termin geöffnet.
    const check = dueReminders([appt()], '2026-03-10T12:30:00Z');
    expect(check.notify).toHaveLength(1);
    expect(check.notify[0].kind).toBe('1h');
    expect(check.markFired.sort()).toEqual(['appt:a1:1h', 'appt:a1:24h']);
  });

  it('wiederholt eine bereits ausgelöste Erinnerung nicht', () => {
    const fired = new Set(['appt:a1:24h', 'appt:a1:1h']);
    expect(dueReminders([appt()], '2026-03-10T12:30:00Z', fired).notify).toHaveLength(0);
  });

  it('erinnert nicht an abgesagte Termine', () => {
    const a = appt({ cancelledAt: '2026-03-08T09:00:00Z' });
    expect(dueReminders([a], '2026-03-10T12:30:00Z')).toEqual({ notify: [], markFired: [] });
  });

  it('erinnert nicht an vergangene oder gerade laufende Termine', () => {
    expect(dueReminders([appt()], '2026-03-10T13:00:00Z').notify).toHaveLength(0);
    expect(dueReminders([appt()], '2026-03-11T09:00:00Z').notify).toHaveLength(0);
  });

  it('achtet auf die einzeln abschaltbaren Schalter', () => {
    const ohne24 = appt({ remind24h: false });
    expect(dueReminders([ohne24], '2026-03-09T14:00:00Z').notify).toHaveLength(0);
    expect(dueReminders([ohne24], '2026-03-10T12:30:00Z').notify[0].kind).toBe('1h');

    const ohne1 = appt({ remind1h: false });
    expect(dueReminders([ohne1], '2026-03-10T12:30:00Z').notify[0].kind).toBe('24h');

    const stumm = appt({ remind24h: false, remind1h: false });
    expect(dueReminders([stumm], '2026-03-10T12:30:00Z')).toEqual({ notify: [], markFired: [] });
  });

  it('rechnet über den Sommerzeitwechsel in echten Stunden, nicht in Wanduhrzeit', () => {
    // Termin am 29.03.2026 um 12:00 deutscher Sommerzeit (= 10:00 UTC).
    // In der Nacht davor wird die Uhr vorgestellt.
    const a = appt({ startAt: '2026-03-29T12:00:00+02:00' });

    // Gleiche Wanduhrzeit am Vortag (12:00 Winterzeit = 11:00 UTC) sind nur
    // 23 echte Stunden — die Erinnerung ist also schon fällig.
    expect(dueReminders([a], '2026-03-28T12:00:00+01:00').notify).toHaveLength(1);

    // Eine Minute vor dem echten 24-Stunden-Punkt noch nicht …
    expect(dueReminders([a], '2026-03-28T10:59:00+01:00').notify).toHaveLength(0);
    // … eine Minute danach schon.
    expect(dueReminders([a], '2026-03-28T11:01:00+01:00').notify).toHaveLength(1);
  });

  it('verarbeitet mehrere Termine und sortiert nach Beginn', () => {
    const list = [
      appt({ id: 'spaet', startAt: '2026-03-10T16:00:00Z' }),
      appt({ id: 'frueh', startAt: '2026-03-10T14:00:00Z' }),
    ];
    const check = dueReminders(list, '2026-03-10T13:00:00Z');
    expect(check.notify.map((r) => r.appointmentId)).toEqual(['frueh', 'spaet']);
  });

  it('verschluckt sich nicht an unbrauchbaren Zeitpunkten', () => {
    expect(dueReminders([appt({ startAt: 'kaputt' })], '2026-03-10T12:00:00Z').notify).toEqual([]);
    expect(dueReminders([appt()], 'kaputt')).toEqual({ notify: [], markFired: [] });
  });

  it('schreibt einen verständlichen deutschen Text', () => {
    const a = appt({ title: 'Familie Meyer', location: 'bei uns' });
    const r = dueReminders([a], '2026-03-10T12:30:00Z').notify[0];
    expect(r.title).toBe('Termin in 30 Minuten: Familie Meyer');
    expect(r.body).toContain('bei uns');
  });

  it('nimmt ohne eigenen Titel die Art des Termins', () => {
    const r = dueReminders([appt()], '2026-03-10T12:30:00Z').notify[0];
    expect(r.title).toContain('Kennenlernen');
  });
});

