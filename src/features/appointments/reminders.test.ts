describe('pendingFollowUps', () => {
  it('fragt nur bei vergangenen, offenen Terminen nach', () => {
    const list = [
      appt({ id: 'vorbei', startAt: '2026-03-09T13:00:00Z' }),
      appt({ id: 'kommt', startAt: '2026-03-11T13:00:00Z' }),
      appt({ id: 'erledigt', startAt: '2026-03-09T10:00:00Z', followUpDone: true }),
      appt({ id: 'abgesagt', startAt: '2026-03-09T10:00:00Z', cancelledAt: '2026-03-08T10:00:00Z' }),
    ];
    expect(pendingFollowUps(list, '2026-03-10T13:00:00Z').map((a) => a.id)).toEqual(['vorbei']);
  });

  it('wartet das Ende eines laufenden Termins ab', () => {
    const a = appt({ startAt: '2026-03-10T12:30:00Z', durationMin: 60 });
    expect(pendingFollowUps([a], '2026-03-10T13:00:00Z')).toHaveLength(0);
    expect(pendingFollowUps([a], '2026-03-10T13:31:00Z')).toHaveLength(1);
  });

  it('hört nach 30 Tagen auf zu fragen', () => {
    const a = appt({ startAt: '2026-02-01T13:00:00Z' });
    expect(pendingFollowUps([a], '2026-03-10T13:00:00Z')).toHaveLength(0);
  });

  it('zeigt höchstens drei Karten, neueste zuerst', () => {
    const list = [1, 2, 3, 4, 5].map((n) =>
      appt({ id: `a${n}`, startAt: `2026-03-0${n}T13:00:00Z` }),
    );
    const result = pendingFollowUps(list, '2026-03-10T13:00:00Z');
    expect(result.map((a) => a.id)).toEqual(['a5', 'a4', 'a3']);
  });

  it('liefert bei leerer Liste nichts', () => {
    expect(pendingFollowUps([], '2026-03-10T13:00:00Z')).toEqual([]);
  });
});

