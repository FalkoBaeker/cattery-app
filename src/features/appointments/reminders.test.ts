describe('buildCalendarEntries', () => {
  const names = {
    interests: new Map([['i1', 'Familie Meyer']]),
    cats: new Map([['c1', 'Mina']]),
    litters: new Map([['l1', 'Wurf von Mina']]),
    kittens: new Map([['k1', 'Rot']]),
  };

  it('liefert bei völlig leeren Quellen eine leere Liste', () => {
    expect(buildCalendarEntries({}, '2026-03-10')).toEqual([]);
    expect(
      buildCalendarEntries(
        { appointments: [], careTasks: [], litters: [], healthTests: [], breedingUses: [] },
        '2026-03-10',
      ),
    ).toEqual([]);
  });

  it('führt alle fünf Quellen zusammen', () => {
    const entries = buildCalendarEntries(
      {
        appointments: [appt({ startAt: '2026-03-10T13:00:00Z', interestId: 'i1' })],
        careTasks: [task({ dueDate: '2026-03-12', litterId: 'l1' })],
        litters: [litter({ dueDate: '2026-03-20' })],
        healthTests: [healthTest({ nextDueDate: '2026-03-15' })],
        breedingUses: [breedingUse({ deadlineDate: '2026-07-15' })],
        names,
      },
      '2026-03-10',
    );
    const sources = new Set(entries.map((e) => e.source));
    expect(sources).toEqual(
      new Set(['appointment', 'care_task', 'litter_due', 'health_test', 'breeding_use']),
    );
  });

  it('hängt den Bezug als Klarnamen an', () => {
    const entries = buildCalendarEntries(
      {
        appointments: [appt({ interestId: 'i1' })],
        careTasks: [task({ litterId: 'l1' }), task({ id: 't2', kittenId: 'k1', litterId: 'l1' })],
        healthTests: [healthTest()],
        names,
      },
      '2026-03-10',
    );
    expect(entries.find((e) => e.key === 'appt:a1')?.relation).toBe('Familie Meyer');
    expect(entries.find((e) => e.key === 'task:t1')?.relation).toBe('Wurf von Mina');
    // Das Kitten ist genauer als der Wurf.
    expect(entries.find((e) => e.key === 'task:t2')?.relation).toBe('Rot');
    expect(entries.find((e) => e.key === 'health:h1')?.relation).toBe('Mina');
  });

  it('kommt ohne Namensverzeichnis aus', () => {
    const entries = buildCalendarEntries({ appointments: [appt({ interestId: 'i1' })] }, '2026-03-10');
    expect(entries[0].relation).toBeUndefined();
  });

  it('zeigt abgesagte Termine weiterhin, aber gekennzeichnet', () => {
    const entries = buildCalendarEntries(
      { appointments: [appt({ cancelledAt: '2026-03-09T10:00:00Z' })] },
      '2026-03-10',
    );
    // Die Beschriftung „Abgesagt" setzt der Bildschirm aus diesem Merker;
    // der Eintrag selbst trägt bewusst keinen eigenen Text.
    expect(entries[0].cancelled).toBe(true);
    expect(entries[0].tone).toBe('neutral');
  });

  it('blendet erledigte und übersprungene Fahrplan-Punkte aus', () => {
    const entries = buildCalendarEntries(
      {
        careTasks: [
          task({ id: 'offen' }),
          task({ id: 'fertig', doneAt: '2026-03-30' }),
          task({ id: 'uebersprungen', skipped: true }),
        ],
      },
      '2026-03-10',
    );
    expect(entries.map((e) => e.key)).toEqual(['task:offen']);
  });

  it('kennzeichnet überfällige Punkte', () => {
    const entries = buildCalendarEntries({ careTasks: [task({ dueDate: '2026-03-01' })] }, '2026-03-10');
    expect(entries[0].overdue).toBe(true);
    expect(entries[0].tone).toBe('warn');
  });

  it('zeigt Geburtstermine nur für gedeckte und trächtige Würfe ohne Geburtsdatum', () => {
    const list = [
      litter({ id: 'traechtig', status: 'pregnant' }),
      litter({ id: 'gedeckt', status: 'mated' }),
      litter({ id: 'geplant', status: 'planned' }),
      litter({ id: 'geboren', status: 'born', birthDate: '2026-03-18' }),
      litter({ id: 'ohne-termin', dueDate: undefined }),
    ];
    const entries = buildCalendarEntries({ litters: list }, '2026-03-10');
    expect(entries.map((e) => e.key).sort()).toEqual(['litter:gedeckt', 'litter:traechtig']);
  });

  it('nimmt Gesundheitstests nur mit Ablaufdatum auf', () => {
    const entries = buildCalendarEntries(
      { healthTests: [healthTest(), healthTest({ id: 'h2', nextDueDate: undefined })] },
      '2026-03-10',
    );
    expect(entries.map((e) => e.key)).toEqual(['health:h1']);
  });

  it('benennt freie Gesundheitstests nach ihrem eigenen Namen', () => {
    const entries = buildCalendarEntries(
      { healthTests: [healthTest({ kind: 'other', label: 'Blutbild' })] },
      '2026-03-10',
    );
    expect(entries[0].title).toBe('Blutbild fällig');
  });

  it('erzeugt zur Zuchtnutzung die Frist und die Vorwarnungen bei 6, 3 und 1 Monat', () => {
    const entries = buildCalendarEntries(
      { breedingUses: [breedingUse({ deadlineDate: '2026-07-15', startDate: '2025-01-15' })] },
      '2026-03-10',
    );
    const byKey = Object.fromEntries(entries.map((e) => [e.key, e.date]));
    expect(byKey['breeding:b1:deadline']).toBe('2026-07-15');
    expect(byKey['breeding:b1:warn6']).toBe('2026-01-15');
    expect(byKey['breeding:b1:warn3']).toBe('2026-04-15');
    expect(byKey['breeding:b1:warn1']).toBe('2026-06-15');
  });

  it('lässt Vorwarnungen vor dem Fristbeginn weg', () => {
    const entries = buildCalendarEntries(
      { breedingUses: [breedingUse({ startDate: '2026-03-01', deadlineDate: '2026-07-15' })] },
      '2026-03-10',
    );
    expect(entries.map((e) => e.key).sort()).toEqual([
      'breeding:b1:deadline',
      'breeding:b1:warn1',
      'breeding:b1:warn3',
    ]);
  });

  it('rechnet Vorwarnungen am Monatsende korrekt', () => {
    // 31.03. minus 1 Monat gibt es nicht als 31.02. — es wird der 28.02.
    const entries = buildCalendarEntries(
      { breedingUses: [breedingUse({ startDate: '2024-09-30', deadlineDate: '2026-03-31' })] },
      '2026-03-10',
    );
    const warn1 = entries.find((e) => e.key === 'breeding:b1:warn1');
    expect(warn1?.date).toBe('2026-02-28');
  });

  it('berücksichtigt das Schaltjahr', () => {
    const entries = buildCalendarEntries(
      { breedingUses: [breedingUse({ startDate: '2022-01-01', deadlineDate: '2024-03-31' })] },
      '2024-03-10',
    );
    expect(entries.find((e) => e.key === 'breeding:b1:warn1')?.date).toBe('2024-02-29');
  });

  it('lässt abgeschlossene und abgebrochene Zuchtnutzungen weg', () => {
    const list = [
      breedingUse({ id: 'zu', stage: 'closed' }),
      breedingUse({ id: 'ab', stage: 'cancelled' }),
      breedingUse({ id: 'uebertragen', stage: 'ownership_transferred' }),
      breedingUse({ id: 'laeuft', stage: 'mated' }),
    ];
    const entries = buildCalendarEntries({ breedingUses: list }, '2026-03-10');
    expect(new Set(entries.map((e) => e.key.split(':')[1]))).toEqual(new Set(['laeuft']));
  });

  it('überspringt Termine mit unbrauchbarem Zeitpunkt', () => {
    const entries = buildCalendarEntries({ appointments: [appt({ startAt: 'kaputt' })] }, '2026-03-10');
    expect(entries).toEqual([]);
  });

  it('kommt mit sehr langen Namen zurecht', () => {
    const langer = 'Familie '.repeat(40).trim();
    const entries = buildCalendarEntries(
      {
        appointments: [appt({ interestId: 'i1' })],
        names: { interests: new Map([['i1', langer]]) },
      },
      '2026-03-10',
    );
    expect(entries[0].relation).toBe(langer);
  });
});

describe('compareEntries und groupByDay', () => {
  function entry(over: Partial<CalendarEntry> = {}): CalendarEntry {
    return {
      key: 'x',
      source: 'appointment',
      date: '2026-03-10',
      title: 'Etwas',
      icon: 'calendar',
      tone: 'neutral',
      ...over,
    };
  }

  it('sortiert nach Tag, dann ganztägig vor Uhrzeit, dann nach Uhrzeit', () => {
    const list = [
      entry({ key: 'spaet', at: '2026-03-10T16:00:00Z' }),
      entry({ key: 'ganztags' }),
      entry({ key: 'morgen', date: '2026-03-11' }),
      entry({ key: 'frueh', at: '2026-03-10T08:00:00Z' }),
    ];
    expect([...list].sort(compareEntries).map((e) => e.key)).toEqual([
      'ganztags',
      'frueh',
      'spaet',
      'morgen',
    ]);
  });

  it('sortiert bei gleicher Uhrzeit stabil nach Titel', () => {
    const list = [
      entry({ key: 'b', title: 'Zweiter', at: '2026-03-10T08:00:00Z' }),
      entry({ key: 'a', title: 'Erster', at: '2026-03-10T08:00:00Z' }),
    ];
    expect([...list].sort(compareEntries).map((e) => e.key)).toEqual(['a', 'b']);
  });

  it('gruppiert nach Tag', () => {
    const days = groupByDay([
      entry({ key: 'a', date: '2026-03-11' }),
      entry({ key: 'b', date: '2026-03-10' }),
      entry({ key: 'c', date: '2026-03-10' }),
    ]);
    expect(days.map((d) => d.date)).toEqual(['2026-03-10', '2026-03-11']);
    expect(days[0].entries).toHaveLength(2);
  });

  it('gruppiert eine leere Liste zu nichts', () => {
    expect(groupByDay([])).toEqual([]);
  });

  it('trennt Vergangenheit und Zukunft, heute gehört zur Zukunft', () => {
    const { upcoming, past } = splitCalendar(
      [
        entry({ key: 'gestern', date: '2026-03-09' }),
        entry({ key: 'heute', date: '2026-03-10' }),
        entry({ key: 'morgen', date: '2026-03-11' }),
        entry({ key: 'vorgestern', date: '2026-03-08' }),
      ],
      '2026-03-10',
    );
    expect(upcoming.map((d) => d.date)).toEqual(['2026-03-10', '2026-03-11']);
    // Vergangenes rückwärts: das Jüngste zuerst.
    expect(past.map((d) => d.date)).toEqual(['2026-03-09', '2026-03-08']);
  });

  it('zeigt ganztägige Einträge als solche an', () => {
    expect(entryTimeText(entry())).toBe('ganztägig');
    expect(entryTimeText(entry({ at: '2026-03-10T08:00:00Z' }))).toMatch(/^\d{2}:\d{2}$/);
  });
});

