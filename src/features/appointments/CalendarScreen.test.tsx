import { beforeEach, describe, expect, it } from 'vitest';
import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter, Route, Routes } from 'react-router';
import type { ReactNode } from 'react';
import { ConfirmProvider, ToastProvider } from '../../ui';
import { db, insert, wipeDatabase } from '../../db/db';
import { CalendarScreen } from './CalendarScreen';

function wrap(ui: ReactNode) {
  return render(
    <ToastProvider>
      <ConfirmProvider>
        <MemoryRouter initialEntries={['/kalender']}>
          <Routes>
            <Route path="/kalender" element={ui} />
          </Routes>
        </MemoryRouter>
      </ConfirmProvider>
    </ToastProvider>,
  );
}

/** Zeitpunkt relativ zu jetzt — bewusst über die lokale Zeit gerechnet. */
function shift(days: number, hour = 14): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(hour, 0, 0, 0);
  return d.toISOString();
}

beforeEach(async () => {
  await wipeDatabase();
});

describe('CalendarScreen', () => {
  it('zeigt erst den Ladezustand und danach den Leerzustand — nie beides verwechselt', async () => {
    wrap(<CalendarScreen />);
    expect(screen.getByText(/Termine werden geladen/)).toBeInTheDocument();
    expect(screen.queryByText('Noch keine Termine')).not.toBeInTheDocument();

    expect(await screen.findByText('Noch keine Termine')).toBeInTheDocument();
    // Ein Weg nach vorn im Leerzustand — und der Fab bleibt trotzdem da.
    expect(screen.getAllByRole('button', { name: 'Termin anlegen' })).toHaveLength(2);
  });

  it('zeigt kommende Termine mit Uhrzeit und Bezug', async () => {
    const interest = await insert(db.interests, {
      name: 'Familie Meyer',
      wishSex: 'any',
      status: 'new',
      sortIndex: 0,
    });
    await insert(db.appointments, {
      kind: 'meet_breeder',
      startAt: shift(1, 14),
      interestId: interest.id,
      remind24h: true,
      remind1h: true,
    });

    wrap(<CalendarScreen />);
    // Innerhalb des 24-Stunden-Fensters steht die Terminart zusätzlich in
    // der Erinnerungskarte. Die eigentliche Terminzeile bleibt über Bezug
    // und Uhrzeit eindeutig prüfbar.
    expect((await screen.findAllByText('Kennenlernen')).length).toBeGreaterThan(0);
    expect(screen.getByText(/Familie Meyer/)).toBeInTheDocument();
    expect(screen.getByText('14:00')).toBeInTheDocument();
    // Morgen ist morgen.
    expect(screen.getByText('Morgen')).toBeInTheDocument();
  });

  it('nimmt auch Fahrplan-Punkte, Geburtstermine und Fristen auf', async () => {
    const mutter = await insert(db.cats, {
      callName: 'Mina',
      sex: 'female',
      breed: 'Russisch Blau',
      status: 'active',
      isOwn: true,
    });
    const wurf = await insert(db.litters, {
      motherId: mutter.id,
      status: 'pregnant',
      dueDate: isoDate(3),
    });
    await insert(db.careTasks, {
      kind: 'deworming',
      title: 'Entwurmung 1. Mal',
      dueDate: isoDate(2),
      litterId: wurf.id,
      autoGenerated: true,
    });
    await insert(db.healthTests, {
      catId: mutter.id,
      kind: 'hcm',
      date: isoDate(-180),
      nextDueDate: isoDate(4),
    });

    wrap(<CalendarScreen />);
    expect(await screen.findByText('Entwurmung 1. Mal')).toBeInTheDocument();
    expect(screen.getByText('Geburtstermin erwartet')).toBeInTheDocument();
    expect(screen.getByText('HCM (Herzultraschall) fällig')).toBeInTheDocument();
    // Der Bezug kommt aus den anderen Tabellen.
    expect(screen.getAllByText('Wurf von Mina').length).toBeGreaterThan(0);
  });

  it('klappt Vergangenes erst auf Wunsch auf', async () => {
    await insert(db.appointments, {
      kind: 'vet',
      title: 'Impfung Mina',
      startAt: shift(-5, 10),
      remind24h: true,
      remind1h: true,
      followUpDone: true,
    });

    wrap(<CalendarScreen />);
    const toggle = await screen.findByRole('button', { name: /Vergangenes anzeigen \(1\)/ });
    expect(screen.queryByText('Impfung Mina')).not.toBeInTheDocument();

    await userEvent.click(toggle);
    expect(screen.getByText('Impfung Mina')).toBeInTheDocument();
  });

  it('fragt nach einem vergangenen Termin einmal nach und lässt sich wegwischen', async () => {
    const a = await insert(db.appointments, {
      kind: 'meet_kittens',
      startAt: shift(-2, 15),
      remind24h: true,
      remind1h: true,
    });

    wrap(<CalendarScreen />);
    expect(await screen.findByText("Wie war's?")).toBeInTheDocument();

    await userEvent.click(screen.getByRole('button', { name: 'Nicht nachfragen' }));

    await waitFor(async () => {
      const stored = await db.appointments.get(a.id);
      expect(stored?.followUpDone).toBe(true);
    });
    await waitFor(() => expect(screen.queryByText("Wie war's?")).not.toBeInTheDocument());
  });

  it('kündigt einen Termin, der bald ansteht, auch ohne Mitteilung an', async () => {
    const soon = new Date(Date.now() + 30 * 60_000).toISOString();
    await insert(db.appointments, {
      kind: 'pickup',
      title: 'Abholung Rot',
      startAt: soon,
      remind24h: true,
      remind1h: true,
    });

    wrap(<CalendarScreen />);
    expect(await screen.findByText('Steht an')).toBeInTheDocument();
    expect(screen.getByText(/in \d+ Minuten/)).toBeInTheDocument();
    expect(
      screen.getByText(/unabhängig davon, ob eine Mitteilung angekommen ist/),
    ).toBeInTheDocument();
  });

  it('zeigt abgesagte Termine weiter, aber gekennzeichnet', async () => {
    await insert(db.appointments, {
      kind: 'mating',
      title: 'Deckbesuch',
      startAt: shift(2, 11),
      remind24h: true,
      remind1h: true,
      cancelledAt: new Date().toISOString(),
    });

    wrap(<CalendarScreen />);
    expect(await screen.findByText('Abgesagt')).toBeInTheDocument();
  });
});

/** Reines Datum relativ zu heute, in lokaler Zeitzone. */
function isoDate(days: number): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}
